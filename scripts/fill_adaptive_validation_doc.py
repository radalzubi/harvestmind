"""Render docs/validation/ADAPTIVE_ENGINE_VALIDATION.md from
artifacts/adaptive_transition_validation.json. Every number in the document
comes from the artifact; nothing is typed by hand."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "artifacts" / "adaptive_transition_validation.json"
OUT = ROOT / "docs" / "validation" / "ADAPTIVE_ENGINE_VALIDATION.md"

DESCR = {
    "A_progressive_disruption": "fill on half the suppliers drifts 1.0 → 0.6 over 8 weeks (onset week 62), trough to week 76, recovery by 84",
    "B_sudden_shock": "fill 0.5 and lead ×2.5 on half the suppliers for 6 weeks from week 67, no warning",
    "C_false_alarm": "one bad week (fill 0.55) at week 67, then normal",
    "D_demand_only_shock": "demand ×1.6 for 6 weeks from week 66; supply untouched",
    "E_recovery": "disruption weeks 46–58 on half the suppliers, ended two weeks before the run starts",
    "F_asymmetric_suppliers": "one supplier disrupted (fill 0.55, lead ×2) weeks 66–78, the rest normal",
    "easy_slack": "A_stable, five weeks of cover, nothing happens",
}
EXPECT = {
    "A_progressive_disruption": "detect on the affected suppliers within a few reviews of the trough, tighten commit window, not on the unaffected",
    "B_sudden_shock": "detect within two reviews, posture tightens, unwinds after the episode",
    "C_false_alarm": "no posture flip, no cost worse than the incumbent",
    "D_demand_only_shock": "supply state stays calm; demand evidence, not supply posture",
    "E_recovery": "starts disrupted, unwinds within the run, commit window recovers",
    "F_asymmetric_suppliers": "affected supplier's SKUs flagged, portfolio posture proportionate to their value share",
    "easy_slack": "incumbent retained, low churn, no flags",
}


def pct(x):
    return "n/a" if x is None else f"{x:+.1%}"


def main() -> int:
    if not ART.exists():
        print(f"missing {ART}", file=sys.stderr)
        return 1
    d = json.loads(ART.read_text())
    fz, summ, pols = d["frozen"], d["summary"], d["policies"]
    L = ["# Adaptive Engine Validation", "",
         "*Generated by `scripts/fill_adaptive_validation_doc.py` from "
         "`artifacts/adaptive_transition_validation.json`. Do not edit numbers by hand.*", "",
         "## Design (frozen before the evaluation seeds were run)", "",
         f"- horizon {fz['horizon']} weeks, review every {fz['review']} weeks, training window {fz['train']} weeks, "
         f"run {fz['run_periods']} weeks from absolute week {fz['start']}, {fz['scenarios']} scenarios",
         f"- evaluation seeds {fz['eval_seeds']} (unseen during development; the seeds used while building the "
         "engine were 0–9)",
         f"- safe gate: {fz['safe']}",
         f"- policies: {', '.join(pols)}; every policy closed-loop on identical realised paths, one settlement",
         "- `adaptive_sp` = state-conditioned scenarios + posture-driven anchoring, CVaR, trust region and "
         "plan-stability; `adaptive_safe` = the safe gate with the posture's thresholds and candidate set "
         "(incumbent retained unless a candidate is evidenced); `safe_selected` = the previous gate without a posture",
         "- no fold is filtered on its outcome; negative results are kept", "",
         f"Total wall time {d.get('elapsed_s', 0)/60:.0f} min.", "",
         "## Transition tests", ""]
    for name, cfg in fz["tests"].items():
        if name not in summ:
            continue
        L += [f"### {name}", "", f"*Scenario:* {DESCR.get(name, '')}  ", f"*Expected:* {EXPECT.get(name, '')}", "",
              "| policy | mean vs incumbent | worst | best | win rate | fill | plan churn |",
              "|---|---|---|---|---|---|---|"]
        for pol in pols:
            if pol == "incumbent" or pol not in summ[name]:
                continue
            s = summ[name][pol]
            L.append(f"| {pol} | {pct(s.get('mean'))} | {pct(s.get('worst'))} | {pct(s.get('best'))} | "
                     f"{s.get('win_rate', 0):.0%} | {s.get('fill', 0):.3f} | {s.get('churn', 0):.2f} |")
        for pol in ("adaptive_sp", "adaptive_safe"):
            tr = summ[name].get(pol, {}).get("transition")
            if tr:
                lags = [x for x in tr["detection_lag_weeks"] if x is not None]
                L += ["", f"*State trajectory ({pol}):* peak p(disruptive) {tr.get('peak_p_affected', 0):.2f} on the "
                          f"affected suppliers' SKUs, {tr.get('peak_p_unaffected', 0):.2f} on the others, "
                          f"{tr.get('peak_p_disruptive', 0):.2f} portfolio; "
                          f"detection lag from onset {lags if lags else 'not detected / no onset'} weeks; "
                          f"posture flips per run {tr['posture_flips']:.1f}; weeks in disrupted posture "
                          f"{tr['weeks_disrupted_posture']:.0f}; smallest commit window {tr['min_commit_window']}; "
                          f"final p(disruptive) {tr['final_p_disruptive']:.2f}."]
                break
        L.append("")
    # per-run detail with affected/unaffected
    L += ["## Per-run state detail", "",
          "| test | seed | policy | peak p affected | peak p unaffected | detection week | flips | disrupted weeks | min commit |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in d["runs"]:
        for pol in ("adaptive_safe",):
            tr = r["policy"].get(pol, {}).get("transition")
            if not tr:
                continue
            L.append(f"| {r['test']} | {r['seed']} | {pol} | {tr.get('peak_p_affected', 0):.2f} | "
                     f"{(tr.get('peak_p_unaffected') or 0):.2f} | {tr.get('detection_week')} | {tr['posture_flips']} | "
                     f"{tr['weeks_disrupted_posture']} | {tr['min_commit_window']} |")
    L += ["", "## Selections (adaptive_safe)", "", "| test | seed | selections |", "|---|---|---|"]
    for r in d["runs"]:
        sel = r["policy"].get("adaptive_safe", {}).get("selections")
        if sel:
            L.append(f"| {r['test']} | {r['seed']} | {sel} |")
    L += ["", "## What the tables show (qualitative; the numbers above are the evidence)", "",
          "- **Supply-side transitions (A, B, C, easy).** The standalone stochastic optimizer and the anchored "
          "candidate lose heavily to the incumbent on every seed: they re-plan into the disruption with wide "
          "scenarios and carry stock the incumbent does not. The posture-driven `adaptive_sp` stays within a "
          "few percent of the incumbent because the trust region and anchoring hold it there; `adaptive_safe` "
          "retains the incumbent throughout. On this simulator the incumbent (lead-plus-one cover) is already "
          "competent in supply disruptions, so the honest reading is *no harm done, little value added*.",
          "- **Detection.** The affected suppliers' SKUs cross p(disruptive) 0.5 after the trough is visible in "
          "receipts (lead time plus two bad deliveries plus smoothing). The gradual profile is detected later "
          "than the sudden one, as it should be. The unaffected suppliers stay low, and the false-alarm test "
          "produces at most a brief flag blip on one seed and no cost penalty.",
          "- **Demand-only shock (D) — negative result.** The engine correctly reads *no supply problem* (no "
          "detection, no flags), but the posture's severity is built from disruptive supply regimes and "
          "stress, so the trust region stays tight and `adaptive_sp` captures only a small part of the value "
          "the unconstrained stochastic optimizer finds; the posture-gated `adaptive_safe` does slightly worse "
          "than the incumbent. Demand-regime evidence (DEMAND_VOLATILE, PROMOTION) needs its own severity "
          "channel that widens the *upside* of the trust region. This is left as the first follow-up rather "
          "than fixed here, because fixing it now would mean tuning against the evaluation seeds.",
          "- **Hysteresis.** Posture flips count changes in the number of flagged SKUs between reviews, so "
          "progressive entry and exit register as several small steps rather than thrash; the portfolio-level "
          "flag rarely enters because the value share disrupted stays below the enter threshold in the "
          "asymmetric designs, which is the intended per-SKU behaviour.",
          "- **Easy/slack.** Nothing happens and the engine leaves the operation alone: commit window at its "
          "maximum, no flags, churn at or below the incumbent's.", "",
          "## Reading the results", "",
          "- A positive number is a cost reduction relative to the incumbent on the same realised path; a negative "
          "number is a loss. Worst is the worst seed.",
          "- Detection lag is measured on the SKUs of the suppliers the simulator actually disrupted, from the "
          "profile's onset week to the first review at which their mean p(disruptive) exceeded 0.5. Supply "
          "evidence arrives with the receipt, so the lag includes the lead time.",
          "- `peak p unaffected` is the false-positive check: the estimator should stay low on suppliers "
          "nothing happened to.",
          "- Plan churn is the mean absolute change in executable quantities between consecutive reviews, as a "
          "share of the executable total.",
          "- Everything here is the calibrated synthetic distributor. It has not been run on a real operator's "
          "live data; that remains P0 for commercial claims.", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
