"""Do the leading indicators actually lead?

Real public history only. The question: does a chokepoint transit index
(Bab el-Mandeb, Suez), news coverage of Red Sea shipping, or the global
supply-chain pressure index move BEFORE Aqaba's import throughput does?
Answered by cross-correlation at leads of 0..12 weeks over (a) the full
span and (b) the Red Sea crisis window (2023-10 .. 2024-09). A best lead of
zero or a weak correlation is a negative result and is reported as such.

Output: artifacts/leading_indicators.json, docs/validation/evidence/leading_indicators.md
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from adaptive.indicators import load_all_indicators  # noqa: E402
from adaptive.leading import disruption_outlook, lead_lag  # noqa: E402
from adaptive.signals import SignalStore, load_portwatch_signals  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
WINDOWS = {"full_span": (datetime(2020, 1, 1, tzinfo=timezone.utc), datetime(2026, 9, 1, tzinfo=timezone.utc)),
           "red_sea_crisis": (datetime(2023, 10, 1, tzinfo=timezone.utc), datetime(2024, 9, 30, tzinfo=timezone.utc)),
           "hormuz_2026": (datetime(2026, 1, 1, tzinfo=timezone.utc), datetime(2026, 9, 1, tzinfo=timezone.utc))}


def main() -> int:
    store = SignalStore(max_age_days=75)
    counts = load_all_indicators(store)
    counts["portwatch_aqaba"] = load_portwatch_signals(store, ROOT / "data/external/portwatch/regional_ports_daily.csv")
    aq = [(s.timestamp, s.value) for s in store.series("port", "AQABA", "throughput_index")]
    cands = {
        "bab_el_mandeb_transits": [(s.timestamp, s.value) for s in store.series("chokepoint", "BAB EL-MANDEB STRAIT", "chokepoint_transit_index")],
        "suez_transits": [(s.timestamp, s.value) for s in store.series("chokepoint", "SUEZ CANAL", "chokepoint_transit_index")],
        "red_sea_news": [(s.timestamp, s.value) for s in store.series("topic", "RED_SEA_SHIPPING", "conflict_index")],
        "gscpi": [(s.timestamp, s.value) for s in store.series("region", "GLOBAL", "gscpi")],
        "fuel_index": [(s.timestamp, s.value) for s in store.series("region", "GLOBAL", "fuel_index")],
    }
    out: dict = {"loaded": counts, "n_aqaba_monthly": len(aq), "windows": {}, "outlook_path": []}
    for wname, (a, b) in WINDOWS.items():
        aq_w = [(d, v) for d, v in aq if a <= d <= b]
        res = {}
        for name, xs in cands.items():
            xs_w = [(d, v) for d, v in xs if a <= d <= b]
            if name in ("gscpi", "fuel_index"):
                # pressure indices: expect NEGATIVE correlation with throughput; flip the sign for a common reading
                xs_w = [(d, -v) for d, v in xs_w]
            res[name] = lead_lag(xs_w, aq_w, max_lead_weeks=12)
        out["windows"][wname] = res
    # what the outlook would have said month by month through the Red Sea crisis
    for m in range(0, 24):
        y, mo = 2023 + (9 + m) // 12, (9 + m) % 12 + 1
        as_of = datetime(y, mo, 15, tzinfo=timezone.utc)
        o = disruption_outlook(store, "red_sea", as_of)
        out["outlook_path"].append({"as_of": as_of.strftime("%Y-%m"), "risk": round(o.risk, 3), "quality": round(o.quality, 2),
                                    "top": sorted(o.contributions.items(), key=lambda kv: -kv[1])[:2], "missing": o.missing})
    art = ROOT / "artifacts" / "leading_indicators.json"
    art.parent.mkdir(exist_ok=True)
    art.write_text(json.dumps(out, indent=1, default=str))
    # evidence doc
    L = ["# Leading indicators: do they lead Aqaba throughput?", "",
         "*Generated by `scripts/validate_leading_indicators.py` from real public series (IMF PortWatch, GDELT, NY Fed, FRED).*", "",
         "Correlation between each indicator at week t and the Aqaba monthly import index at week t+lead. "
         "`leads` is true only when the best lead is positive and beats the contemporaneous correlation by more than 0.05.", ""]
    for wname, res in out["windows"].items():
        L += [f"## {wname}", "", "| indicator | r at lead 0 | best lead (weeks) | r at best lead | n | leads? |", "|---|---|---|---|---|---|"]
        for name, r in res.items():
            if r.get("n") == 0 or "by_lead" not in r:
                L.append(f"| {name} | n/a | n/a | n/a | 0 | insufficient overlap |")
                continue
            L.append(f"| {name} | {r['r_at_zero'] if r['r_at_zero'] is None else round(r['r_at_zero'], 2)} | {r['best_lead_weeks']} | "
                     f"{r['best_r']:.2f} | {r['by_lead'][r['best_lead_weeks']]['n']} | {'yes' if r['leads'] else 'no'} |")
        L.append("")
    L += ["## Outlook the engine would have produced through the Red Sea crisis", "",
          "| month | risk | quality | top contributions | missing feeds |", "|---|---|---|---|---|"]
    for row in out["outlook_path"]:
        L.append(f"| {row['as_of']} | {row['risk']:.2f} | {row['quality']:.2f} | {row['top']} | {len(row['missing'])} |")
    L += ["", "## Reading", "",
          "- A positive lead with a materially higher correlation than at lead 0 is evidence the indicator anticipates the port; "
          "a best lead of 0 means it is coincident (still useful as fast confirmation, not as a forecast).",
          "- Monthly port throughput against weekly indicators limits the resolution; n is the number of aligned weeks.",
          "- GDELT coverage is only available for the trailing 24 months from the fetch date, so the crisis window may show insufficient overlap for it.",
          "- The outlook weights are ASSUMED design constants; this document is the check on them, not a fit.", ""]
    doc = ROOT / "docs" / "validation" / "evidence" / "leading_indicators.md"
    doc.parent.mkdir(parents=True, exist_ok=True)
    doc.write_text("\n".join(L))
    print(f"wrote {art} and {doc}")
    for wname, res in out["windows"].items():
        print(wname, {k: (v.get("best_lead_weeks"), round(v.get("best_r", 0), 2), v.get("leads")) for k, v in res.items()})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
